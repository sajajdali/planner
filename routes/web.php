        Route::post('/tasks/reorder', [PlannerController::class, 'reorderTasks']);
        Route::post('/tasks/{task}/complete', [PlannerController::class, 'complete']);
        Route::post('/tasks/{task}/refer', [PlannerController::class, 'referTask']);
