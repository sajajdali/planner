<?php

use App\Http\Controllers\Api\AuthController;
use App\Http\Controllers\Api\PlannerController;
use Illuminate\Support\Facades\Route;

Route::get('/{any?}', function () {
    return view('welcome');
})->where('any', '^(?!api).*$');

